def window_grid(b, x0, x1, z0, z1, y, depth, seed, cols=None, rows=None,
                lit_ratio=0.22, cool_ratio=0.10, recess=0.12):
    """A band of recessed windows on a facade plane at `y`, facing -Y or +Y
    depending on the sign of `depth`. Dark glass everywhere, a seeded subset
    warm-lit and a smaller subset cool-lit, so no two facades light the same
    and nothing ever flickers (the choice is baked into geometry)."""
    w = x1 - x0
    h = z1 - z0
    if w <= 0.4 or h <= 0.3:
        return
    cols = cols or max(1, int(w / 1.9))
    rows = rows or max(1, int(h / 1.6))
    cw = (w / cols) * 0.62
    ch = (h / rows) * 0.60
    for r in range(rows):
        for c in range(cols):
            cx = x0 + (c + 0.5) * (w / cols)
            cz = z0 + (r + 0.5) * (h / rows)
            s = seed + r * 37 + c * 13
            roll = rnd(s)
            if roll > 1.0 - lit_ratio:
                mat = "ARGUS_WarmGlass"
            elif roll < cool_ratio:
                mat = "ARGUS_CoolGlass"
            else:
                mat = "ARGUS_BlackGlass"
            # Reveal (the dark surround) then the glass itself, set back into
            # it -- this is what gives a facade depth at grazing light.
            b.m("ARGUS_DarkAlloy").box(cx, y + depth * 0.5, cz, cw + 0.14, abs(depth), ch + 0.14)
            b.m(mat).box(cx, y + depth * recess, cz, cw, abs(depth) * 0.35, ch)


def floor_band(b, cx, cy, w, d, z, thickness=0.26, overhang=0.10, mat="ARGUS_Steel"):
    """A floor slab that reads from outside as a horizontal shadow line."""
    b.m(mat).box(cx, cy, z, w + overhang * 2, d + overhang * 2, thickness, bevel=0.02)


def corner_columns(b, cx, cy, w, d, z0, z1, size=0.42, mat="ARGUS_DarkAlloy"):
    h = z1 - z0
    for sx in (-1, 1):
        for sy in (-1, 1):
            b.m(mat).box(cx + sx * (w / 2 - size / 2), cy + sy * (d / 2 - size / 2),
                         z0 + h / 2, size, size, h, bevel=0.03)


def parapet(b, cx, cy, w, d, z, height=0.75, thickness=0.30, mat="ARGUS_Concrete"):
    """A real roof edge wall -- the single cheapest thing that stops a roof
    reading as the flat top of a box."""
    for sy in (-1, 1):
        b.m(mat).box(cx, cy + sy * (d / 2 - thickness / 2), z + height / 2, w, thickness, height, bevel=0.02)
    for sx in (-1, 1):
        b.m(mat).box(cx + sx * (w / 2 - thickness / 2), cy, z + height / 2,
                     thickness, d - thickness * 2, height, bevel=0.02)


def entrance(b, cx, cy, w, z0, face=-1, accent="ARGUS_Cyan", canopy=True):
    """A ground-floor entrance at real door scale: recessed reveal, glazed
    doors, a canopy and a light strip. This is the scale reference that tells
    a viewer how big the whole building is."""
    y = cy + face * 0.0
    b.m("ARGUS_DarkAlloy").box(cx, y, z0 + (DOOR_H + 0.7) / 2, w + 0.9, 0.55, DOOR_H + 0.7)
    b.m("ARGUS_WarmGlass").box(cx, y + face * 0.24, z0 + DOOR_H / 2, w, 0.14, DOOR_H)
    b.m("ARGUS_Steel").box(cx, y + face * 0.24, z0 + DOOR_H / 2, 0.10, 0.18, DOOR_H)
    if canopy:
        b.m("ARGUS_Steel").box(cx, y + face * 0.85, z0 + DOOR_H + 0.62, w + 1.8, 1.7, 0.16, bevel=0.03)
        b.m(accent).box(cx, y + face * 1.62, z0 + DOOR_H + 0.54, w + 1.5, 0.07, 0.07)
    # Steps up from the pavement.
    for i in range(2):
        b.m("ARGUS_Concrete").box(cx, y + face * (0.9 + i * 0.45), z0 - 0.06 - i * 0.11,
                                  w + 1.6 - i * 0.3, 0.9, 0.12)


def roof_plant(b, cx, cy, w, d, z, seed, accent="ARGUS_Cyan"):
    """Rooftop HVAC, vents, a stair head and an antenna. Rooflines are what an
    isometric camera sees most of -- an empty one reads as an unfinished box."""
    units = 2 if w < 9 else 3
    for i in range(units):
        ux = cx - w * 0.26 + (i * w * 0.52) / max(1, units - 1)
        uy = cy + (rnd(seed + i * 7) - 0.5) * d * 0.4
        uw = 1.1 + rnd(seed + i) * 0.7
        b.m("ARGUS_Steel").box(ux, uy, z + 0.42, uw, 1.35, 0.84, bevel=0.03)
        b.m("ARGUS_DarkAlloy").cyl(ux, uy, z + 0.90, 0.30, 0.30, 0.10, segs=8)
    # Stair / lift head -- the little block that makes a roof believable.
    b.m("ARGUS_Concrete").box(cx + w * 0.28, cy - d * 0.26, z + 1.15, 2.1, 2.1, 2.3, bevel=0.03)
    b.m(accent).box(cx + w * 0.28, cy - d * 0.26 - 1.06, z + 1.9, 1.2, 0.06, 0.06)
    # Vent stack.
    b.m("ARGUS_Steel").cyl(cx - w * 0.30, cy + d * 0.26, z + 0.75, 0.30, 0.36, 1.5, segs=8)


def antenna(b, cx, cy, z, h, accent="ARGUS_Cyan", dish=True):
    b.m("ARGUS_Steel").cyl(cx, cy, z + h / 2, 0.07, 0.11, h, segs=6)
    if dish:
        b.m("ARGUS_Steel").cyl(cx, cy, z + h * 0.78, 0.36, 0.12, 0.10, segs=10)
    b.m(accent).cyl(cx, cy, z + h + 0.06, 0.09, 0.09, 0.12, segs=6)


def light_strip(b, cx, cy, w, d, z, accent="ARGUS_Cyan", t=0.07):
    """A thin emissive line around a mass -- the city's main light language.
    Never a glowing wall (accents, not paint)."""
    for sy in (-1, 1):
        b.m(accent).box(cx, cy + sy * d / 2, z, w, t, t)
    for sx in (-1, 1):
        b.m(accent).box(cx + sx * w / 2, cy, z, t, d, t)


def sign_plate(b, cx, cy, cz, w, h, face=-1, accent="ARGUS_Cyan"):
    """A physically-mounted sign: a dark backing plate standing off the wall
    with an emissive face. Text is applied at runtime as a canvas texture on
    the emissive face's own quad (no giant DOM labels)."""
    b.m("ARGUS_DarkAlloy").box(cx, cy, cz, w + 0.3, 0.16, h + 0.3)
    b.m(accent).box(cx, cy + face * 0.13, cz, w, 0.06, h)
    for sx in (-1, 1):
        b.m("ARGUS_Steel").box(cx + sx * (w / 2 + 0.05), cy + face * -0.10, cz, 0.08, 0.22, 0.08)


