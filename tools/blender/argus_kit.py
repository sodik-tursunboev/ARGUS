# Deterministic pseudo-random
# --------------------------------------------------------------------------

def rnd(seed):
    """Deterministic value in [0,1) from an integer-ish seed. The SAME formula
    the runtime uses, so a facade generated here and a window lit at runtime
    agree when they share a seed."""
    x = math.sin(seed * 12.9898) * 43758.5453
    return x - math.floor(x)


def rnd_range(seed, lo, hi):
    return lo + rnd(seed) * (hi - lo)


def rnd_pick(seed, items):
    return items[int(rnd(seed) * len(items)) % len(items)]


