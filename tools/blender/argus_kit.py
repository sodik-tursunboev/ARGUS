MANIFEST = []


def _tri_count(objs):
    total = 0
    for o in objs:
        if o.type != "MESH":
            continue
        me = o.data
        for poly in me.polygons:
            total += max(0, len(poly.vertices) - 2)
    return total


def export_glb(objs, subdir, name, extras=None):
    """Export the given objects as one optimized GLB and record it in the
    build manifest the runtime and the budget gate both read."""
    ensure_dirs()
    for o in bpy.context.scene.objects:
        o.select_set(False)
    real = [o for o in objs if o is not None]
    for o in real:
        o.select_set(True)
    if real:
        bpy.context.view_layer.objects.active = real[0]

    path = os.path.join(ASSET_ROOT, subdir, name + ".glb")
    kwargs = dict(
        filepath=path,
        export_format="GLB",
        use_selection=True,
        export_apply=True,
        export_yup=True,
        export_texcoords=False,
        export_normals=True,
        export_tangents=False,
        export_materials="EXPORT",
        export_cameras=False,
        export_lights=False,
        export_extras=True,
    )
    # Animation flags only exist on newer exporters; pass what this build has.
    if extras and extras.get("animations"):
        kwargs.update(
            export_animations=True,
            export_animation_mode="ACTIONS",
            export_bake_animation=True,
            export_optimize_animation_size=True,
            export_frame_range=False,
        )
    else:
        kwargs.update(export_animations=False)

    _call_gltf_export(kwargs)

    tris = _tri_count(real)
    size = os.path.getsize(path)
    entry = {
        "file": "%s/%s.glb" % (subdir, name),
        "name": name,
        "triangles": tris,
        "bytes": size,
        "objects": len(real),
    }
    if extras:
        entry.update({k: v for k, v in sorted(extras.items()) if k != "animations"})
        if extras.get("animations"):
            entry["animations"] = sorted(extras["animations"])
    MANIFEST.append(entry)
    print("EXPORTED %-42s tris=%-7d bytes=%d" % (entry["file"], tris, size))
    return path


def _call_gltf_export(kwargs):
    """Blender's glTF operator drops/renames keywords between releases; retry
    without the unknown ones rather than pinning to a single Blender build."""
    while True:
        try:
            bpy.ops.export_scene.gltf(**kwargs)
            return
        except TypeError as exc:
            msg = str(exc)
            bad = None
            for key in list(kwargs.keys()):
                if key != "filepath" and key in msg:
                    bad = key
                    break
            if bad is None:
                raise
            print("  (exporter has no '%s' on this Blender build; skipping it)" % bad)
            kwargs.pop(bad)


def write_manifest():
    """A stable, sorted manifest -- the runtime's asset registry and the
    budget/determinism gates all read this one file."""
    ensure_dirs()
    path = os.path.join(ASSET_ROOT, "manifest.json")
    payload = {
        "generator": "tools/blender/build_all.py",
        "scale": "1 unit = 1 metre",
        "assets": sorted(MANIFEST, key=lambda e: e["file"]),
        "totals": {
            "files": len(MANIFEST),
            "triangles": sum(e["triangles"] for e in MANIFEST),
            "bytes": sum(e["bytes"] for e in MANIFEST),
        },
    }
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(payload, fh, indent=2, sort_keys=True)
        fh.write("\n")
    print("MANIFEST %s  files=%d tris=%d bytes=%d" % (
        path, payload["totals"]["files"], payload["totals"]["triangles"], payload["totals"]["bytes"]))
    return path
