# Mesh building -- everything goes through bmesh so we get real geometry ops
# (inset, bevel, solidify) instead of bare primitives.
# --------------------------------------------------------------------------

class Part:
    """An accumulating bmesh with one material. Parts are merged per material
    at the end, which is what keeps a whole building at 1-6 draw calls."""

    def __init__(self, material, family=None):
        self.material = material
        self.family = family
        self.bm = bmesh.new()

    def _absorb(self, bm):
        """Merge a scratch bmesh into this part, then free BOTH it and the
        temporary mesh datablock. Without the explicit remove(), a city's
        worth of boxes leaks tens of thousands of mesh datablocks and the
        build slows to a crawl."""
        mesh = bpy.data.meshes.new("__scratch")
        bm.to_mesh(mesh)
        self.bm.from_mesh(mesh)
        bpy.data.meshes.remove(mesh)
        bm.free()

    def box(self, cx, cy, cz, sx, sy, sz, bevel=0.0):
        """A box centred at (cx,cy,cz) with full sizes (sx,sy,sz). Blender is
        Z-up; the glTF exporter converts to the Y-up the runtime expects."""
        bm = bmesh.new()
        bmesh.ops.create_cube(bm, size=1.0)
        bmesh.ops.scale(bm, vec=Vector((sx, sy, sz)), verts=bm.verts)
        if bevel > 0:
            bmesh.ops.bevel(bm, geom=list(bm.verts) + list(bm.edges),
                            offset=bevel, segments=1, affect="EDGES", clamp_overlap=True)
        bmesh.ops.translate(bm, vec=Vector((cx, cy, cz)), verts=bm.verts)
        self._absorb(bm)
        return self

    def cyl(self, cx, cy, cz, r_top, r_bot, h, segs=12, bevel=0.0):
        bm = bmesh.new()
        bmesh.ops.create_cone(bm, cap_ends=True, cap_tris=False, segments=segs,
                              radius1=r_bot, radius2=r_top, depth=h)
        if bevel > 0:
            bmesh.ops.bevel(bm, geom=list(bm.verts) + list(bm.edges),
                            offset=bevel, segments=1, affect="EDGES", clamp_overlap=True)
        bmesh.ops.translate(bm, vec=Vector((cx, cy, cz)), verts=bm.verts)
        self._absorb(bm)
        return self

    def prism(self, cx, cy, cz, r, h, segs=6, rot_z=0.0, bevel=0.0):
        return self.cyl(cx, cy, cz, r, r, h, segs=segs, bevel=bevel) if rot_z == 0 else \
            self._prism_rot(cx, cy, cz, r, h, segs, rot_z, bevel)

    def _prism_rot(self, cx, cy, cz, r, h, segs, rot_z, bevel):
        bm = bmesh.new()
        bmesh.ops.create_cone(bm, cap_ends=True, cap_tris=False, segments=segs,
                              radius1=r, radius2=r, depth=h)
        bmesh.ops.rotate(bm, verts=bm.verts, cent=Vector((0, 0, 0)),
                         matrix=Euler((0, 0, rot_z)).to_matrix())
        if bevel > 0:
            bmesh.ops.bevel(bm, geom=list(bm.verts) + list(bm.edges),
                            offset=bevel, segments=1, affect="EDGES", clamp_overlap=True)
        bmesh.ops.translate(bm, vec=Vector((cx, cy, cz)), verts=bm.verts)
        self._absorb(bm)
        return self

    def frame(self, cx, cy, cz, sx, sy, sz, thickness):
        """A rectangular picture-frame ring in the XZ plane -- the facade
        element that reads as a structural surround rather than a flat panel."""
        t = thickness
        self.box(cx, cy, cz + sz / 2 - t / 2, sx, sy, t)
        self.box(cx, cy, cz - sz / 2 + t / 2, sx, sy, t)
        self.box(cx - sx / 2 + t / 2, cy, cz, t, sy, sz - 2 * t)
        self.box(cx + sx / 2 - t / 2, cy, cz, t, sy, sz - 2 * t)
        return self

    def to_object(self, name, collection):
        mesh = bpy.data.meshes.new(name)
        bmesh.ops.remove_doubles(self.bm, verts=self.bm.verts, dist=1e-5)
        self.bm.normal_update()
        self.bm.to_mesh(mesh)
        self.bm.free()
        self.bm = None
        mesh.materials.append(get_tinted_material(self.material, self.family))
        for poly in mesh.polygons:
            poly.use_smooth = False   # flat-shaded stylized look
        obj = bpy.data.objects.new(name, mesh)
        collection.objects.link(obj)
        return obj


class Builder:
    """Collects geometry into one Part per material, then emits one object per
    material. A building therefore costs as many draw calls as it uses
    distinct materials -- typically 4-6, not one per box."""

    def __init__(self, name, family="neutral"):
        self.name = name
        # The district category this building belongs to. Every STRUCTURAL
        # material requested through m() is resolved to that family's tinted
        # variant, so a whole family shifts hue from one argument instead of
        # every call site naming a colour (visual design).
        self.family = family
        self.parts = {}
        self._order = []

    def m(self, material):
        if material not in self.parts:
            self.parts[material] = Part(material, self.family)
            self._order.append(material)
        return self.parts[material]

    def accent(self, secondary=False):
        """This family's signal colour -- use instead of hard-coding cyan."""
        return family_accent(self.family, secondary)

    def emit(self, collection):
        objs = []
        for material in self._order:          # insertion order == deterministic
            part = self.parts[material]
            if len(part.bm.verts) == 0:
                part.bm.free()
                continue
            name = "%s_%s" % (self.name, tinted_name(material, self.family).replace("ARGUS_", ""))
            objs.append(part.to_object(name, collection))
        return objs


