# DISTRICT COLOUR SEPARATION
#
# The single biggest readability problem with the first city was that every
# building shared one graphite+cyan palette, so the whole scene sank into the
# dark navy HUD behind it. The fix is not "more neon": it is giving each
# district category its own HUE and VALUE band, so districts separate from
# each other and from the UI while staying inside one premium ARGUS language.
#
# Each family supplies (hue-tint rgb multiplier, value lift, accent material).
# Structural materials are tinted through this; emissive accents stay pure.
# --------------------------------------------------------------------------

