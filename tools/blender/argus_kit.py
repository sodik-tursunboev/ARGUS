"""ARGUS AI City -- shared Blender asset kit.

Every asset in hud-v2/public/assets/city/ is generated by these scripts. No
hand-modelling, no downloaded packs: run `build_all.py` and the whole city
rebuilds from source. That is the point -- the assets are code, reviewable
and diffable like the rest of the repo.

Determinism is a hard requirement (a gate checks it): no randomness that is
not seeded and pure, no dict iteration order dependence, no timestamps, no
"now". Two runs from a clean tree must produce byte-identical GLBs.

Run with:
    blender --background --python tools/blender/build_all.py
"""

