# Only STRUCTURAL materials get tinted -- an emissive accent must stay the
# exact signal colour it is, or state colours stop meaning anything.
TINTABLE = ("ARGUS_Graphite", "ARGUS_DarkAlloy", "ARGUS_Steel", "ARGUS_Concrete")


def family_accent(family, secondary=False):
    tint = FAMILY_TINTS.get(family, FAMILY_TINTS["neutral"])
    return tint[3] if secondary else tint[2]


def tinted_name(base, family):
    if family in (None, "neutral") or base not in TINTABLE:
        return base
    return "%s@%s" % (base, family)


def get_tinted_material(base, family):
    """Fetch-or-create the district-tinted variant of a structural material."""
    name = tinted_name(base, family)
    if name == base:
        return get_material(base)
    mat = bpy.data.materials.get(name)
    if mat is not None:
        return mat
    mul, lift, _accent, _second = FAMILY_TINTS[family]
    base_rgb, metal, rough, emit, emit_strength = PALETTE[base]
    rgb = tuple(min(1.0, base_rgb[i] * mul[i] + lift) for i in range(3))
    mat = bpy.data.materials.new(name=name)
    mat.use_nodes = True
    bsdf = _principled(mat)
    _set_input(bsdf, ["Base Color"], (rgb[0], rgb[1], rgb[2], 1.0))
    _set_input(bsdf, ["Metallic"], metal)
    _set_input(bsdf, ["Roughness"], rough)
    if emit is not None:
        _set_input(bsdf, ["Emission Color", "Emission"], (emit[0], emit[1], emit[2], 1.0))
        _set_input(bsdf, ["Emission Strength"], emit_strength)
    else:
        _set_input(bsdf, ["Emission Strength"], 0.0)
    return mat


def _principled(mat):
    return mat.node_tree.nodes.get("Principled BSDF")


def _set_input(node, names, value):
    """Blender renamed several Principled sockets across 3.x/4.x/5.x; try each
    candidate name so these scripts are not pinned to one release."""
    for n in names:
        sock = node.inputs.get(n)
        if sock is not None:
            sock.default_value = value
            return True
    return False


def get_material(name):
    """Fetch-or-create a palette material. Shared across every object in the
    file, so a GLB carries one material per palette entry it actually uses."""
    mat = bpy.data.materials.get(name)
    if mat is not None:
        return mat
    if name not in PALETTE:
        raise KeyError("unknown palette material: %s" % name)
    base, metal, rough, emit, emit_strength = PALETTE[name]
    mat = bpy.data.materials.new(name=name)
    mat.use_nodes = True
    bsdf = _principled(mat)
    _set_input(bsdf, ["Base Color"], (base[0], base[1], base[2], 1.0))
    _set_input(bsdf, ["Metallic"], metal)
    _set_input(bsdf, ["Roughness"], rough)
    if emit is not None:
        _set_input(bsdf, ["Emission Color", "Emission"], (emit[0], emit[1], emit[2], 1.0))
        _set_input(bsdf, ["Emission Strength"], emit_strength)
    else:
        _set_input(bsdf, ["Emission Strength"], 0.0)
    return mat


